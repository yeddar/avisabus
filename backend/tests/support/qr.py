"""Decoding helpers for the QR codes produced by `SegnoQrRenderer` (zxing-cpp, no network).

zxing-cpp reads raster images only, so the SVG QR is rasterised from segno's path: one
horizontal stroke (`h`) per run of dark modules, rows at `y + 0.5`, moves with `M`/`m`.
"""

import io
import re
import xml.etree.ElementTree as ET  # noqa: S405 (parses SVG generated by our own code)
from dataclasses import dataclass

import zxingcpp
from PIL import Image

SVG_NS = "{http://www.w3.org/2000/svg}"
_COMMAND = re.compile(r"([MmHh])([^MmHh]*)")


@dataclass(frozen=True)
class DecodedQr:
    text: str
    ec_level: str


@dataclass(frozen=True)
class SvgQr:
    root: ET.Element
    qr: ET.Element
    """Nested `<svg>` produced by segno."""
    modules: list[list[bool]]
    """Dark modules, including the quiet zone."""
    scale: int

    @property
    def size_px(self) -> int:
        return len(self.modules) * self.scale


def parse_svg(data: bytes) -> SvgQr:
    root = ET.fromstring(data)  # noqa: S314 (SVG generated by our own code)
    (qr,) = root.findall(f"{SVG_NS}svg")
    (path,) = qr.findall(f"{SVG_NS}path")
    scale = int(re.fullmatch(r"scale\((\d+)\)", path.attrib["transform"]).group(1))  # type: ignore[union-attr]
    size = int(qr.attrib["width"]) // scale
    modules = [[False] * size for _ in range(size)]
    x = y = 0.0
    for command, args in _COMMAND.findall(path.attrib["d"]):
        values = [float(v) for v in args.replace(",", " ").split()]
        if command == "M":
            x, y = values
        elif command == "m":
            x, y = x + values[0], y + values[1]
        else:  # "h": dark run on row y - 0.5
            (dx,) = values
            row = int(y)
            for col in range(int(x), int(x + dx)):
                modules[row][col] = True
            x += dx
    return SvgQr(root=root, qr=qr, modules=modules, scale=scale)


def svg_text_lines(svg: SvgQr) -> list[list[str]]:
    """Lines of every `<text>` of the label (one per `<tspan>`, or the text itself)."""
    texts = []
    for text in svg.root.findall(f"{SVG_NS}text"):
        spans = text.findall(f"{SVG_NS}tspan")
        texts.append([span.text or "" for span in spans] if spans else [text.text or ""])
    return texts


def modules_to_image(modules: list[list[bool]], module_px: int = 8) -> Image.Image:
    size = len(modules)
    image = Image.new("L", (size * module_px, size * module_px), 255)
    for row, line in enumerate(modules):
        for col, dark in enumerate(line):
            if dark:
                image.paste(
                    0,
                    (
                        col * module_px,
                        row * module_px,
                        (col + 1) * module_px,
                        (row + 1) * module_px,
                    ),
                )
    return image


def decode_image(image: Image.Image) -> list[DecodedQr]:
    return [
        DecodedQr(text=barcode.text, ec_level=barcode.ec_level)
        for barcode in zxingcpp.read_barcodes(image.convert("L"))
    ]


def decode_svg(data: bytes) -> list[DecodedQr]:
    return decode_image(modules_to_image(parse_svg(data).modules))


def open_png(data: bytes) -> Image.Image:
    image = Image.open(io.BytesIO(data))
    assert image.format == "PNG"
    return image
