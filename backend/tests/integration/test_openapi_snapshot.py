"""The frontend's copy of the OpenAPI document must match the backend (ADR-010).

`frontend/src/shared/api/openapi.json` is generated by `npm run gen:api` and then formatted by
Prettier, so the documents are compared as JSON values, not as text.
"""

import json
from pathlib import Path
from typing import Any

import pytest

from avisabus.adapters.inbound.http.app import openapi_document

FRONTEND_OPENAPI = Path(__file__).resolve().parents[3] / "frontend/src/shared/api/openapi.json"
REGENERATE = "run `npm run gen:api` in frontend/"


def assert_openapi_matches(backend: dict[str, Any], snapshot: Path) -> None:
    if not snapshot.is_file():
        pytest.fail(f"{snapshot} does not exist: {REGENERATE}")
    frontend = json.loads(snapshot.read_text(encoding="utf-8"))
    # Round trip through JSON so both sides have the same types (e.g. tuples → lists).
    if json.loads(json.dumps(backend)) != frontend:
        pytest.fail(f"The OpenAPI document of the backend differs from {snapshot}: {REGENERATE}")


@pytest.mark.spec("passenger_stop_view.AC-02")
def test_frontend_openapi_matches_the_backend() -> None:
    assert_openapi_matches(openapi_document(), FRONTEND_OPENAPI)


@pytest.mark.spec("passenger_stop_view.AC-02")
def test_a_stale_snapshot_fails_asking_to_run_gen_api(tmp_path: Path) -> None:
    document = openapi_document()
    stale = json.loads(json.dumps(document))
    del stale["components"]["schemas"]["ArrivalSchema"]["properties"]["sae_destination"]
    snapshot = tmp_path / "openapi.json"
    snapshot.write_text(json.dumps(stale), encoding="utf-8")

    with pytest.raises(pytest.fail.Exception, match=r"npm run gen:api"):
        assert_openapi_matches(document, snapshot)


@pytest.mark.spec("passenger_stop_view.AC-02")
def test_a_missing_snapshot_fails_asking_to_run_gen_api(tmp_path: Path) -> None:
    with pytest.raises(pytest.fail.Exception, match=r"npm run gen:api"):
        assert_openapi_matches(openapi_document(), tmp_path / "openapi.json")


@pytest.mark.spec("passenger_stop_view.AC-02")
def test_formatting_differences_do_not_count(tmp_path: Path) -> None:
    document = openapi_document()
    snapshot = tmp_path / "openapi.json"
    snapshot.write_text(json.dumps(document, separators=(",", ":")), encoding="utf-8")

    assert_openapi_matches(document, snapshot)
